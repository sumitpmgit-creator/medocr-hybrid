#!/usr/bin/env node
// Runs the whole QA suite and records results per area into results/.
//   results/latest.json  - raw vitest JSON report
//   results/SUMMARY.md   - pass/fail/skip per area + every failing test id
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const QA = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
mkdirSync(path.join(QA, 'results'), { recursive: true });
const out = path.join(QA, 'results/latest.json');
spawnSync(process.execPath, [path.join(QA, 'node_modules/vitest/vitest.mjs'), 'run', '--reporter=json', `--outputFile=${out}`], { cwd: QA, stdio: 'inherit' });
const rep = JSON.parse(readFileSync(out, 'utf8'));

const AREA = { 'harness': 'HARNESS', 'repo': 'REPO', 'routing': 'ROUTING', 'deid': 'DEID', 'scoring': 'SCORING', 'offline': 'OFFLINE' };
const rows = []; const fails = [];
for (const f of rep.testResults) {
  const key = path.basename(f.name).replace('.test.ts', '');
  const area = AREA[key] ?? key;
  const c = { area, passed: 0, failed: 0, skipped: 0 };
  for (const t of f.assertionResults) {
    if (t.status === 'passed') c.passed++;
    else if (t.status === 'failed') { c.failed++; fails.push(`- **${area}** ${t.title}\n  - ${(t.failureMessages?.[0] ?? '').split('\n')[0].slice(0, 300)}`); }
    else c.skipped++;
  }
  if (f.status === 'failed' && !f.assertionResults.length) fails.push(`- **${area}** suite failed to load: ${(f.message ?? '').slice(0, 300)}`);
  rows.push(c);
}
const order = Object.values(AREA);
rows.sort((a, b) => order.indexOf(a.area) - order.indexOf(b.area));
const tot = rows.reduce((t, r) => ({ passed: t.passed + r.passed, failed: t.failed + r.failed, skipped: t.skipped + r.skipped }), { passed: 0, failed: 0, skipped: 0 });
const ts = new Date().toLocaleString('en-IN', { timeZone: 'Asia/Kolkata', hour12: false }) + ' IST';
const md = [
  `# QA results - ${ts}`, '',
  'Generated by `pnpm results` (scripts/record-results.mjs). Skipped = blocked by missing code or deliberately conditional (see TEST_PLAN.md).', '',
  '| Area | Passed | Failed | Skipped |', '|---|---:|---:|---:|',
  ...rows.map((r) => `| ${r.area} | ${r.passed} | ${r.failed} | ${r.skipped} |`),
  `| **Total** | **${tot.passed}** | **${tot.failed}** | **${tot.skipped}** |`, '',
  '## Failing tests', '', ...fails, '',
].join('\n');
writeFileSync(path.join(QA, 'results/SUMMARY.md'), md);
console.log('\n' + md.split('## Failing')[0]);
